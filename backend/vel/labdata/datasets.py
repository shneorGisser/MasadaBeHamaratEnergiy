from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import Any

Num = float | None


@dataclass(frozen=True)
class DTable:
    study_kind: str
    label: str  # e.g. "טבלה 2.4"
    columns: tuple[tuple[str, str], ...]  # (quantity key, unit as written)
    rows: tuple[tuple[Num, ...], ...]  # row index = measurement-set row
    conditions: dict[str, Any] = field(default_factory=dict)
    note: str = ""
    row_notes: dict[int, str] = field(default_factory=dict)
    # fixed-row tables: the set row each transcribed row goes to (default 0, 1, 2, …)
    row_index: tuple[int, ...] | None = None


@dataclass(frozen=True)
class Dataset:
    id: str
    experiment_id: str
    title_he: str
    source_he: str
    tables: tuple[DTable, ...]


def _t(
    kind: str,
    label: str,
    cols: str,
    rows: Sequence[Sequence[Num]],
    **kw: Any,
) -> DTable:
    """cols: "key:unit key:unit …"."""
    columns = tuple(tuple(c.split(":", 1)) for c in cols.split())
    return DTable(kind, label, columns, tuple(tuple(r) for r in rows), **kw)  # type: ignore[arg-type]


